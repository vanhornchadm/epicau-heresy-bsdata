#!/usr/bin/env python3
"""Parametric magnetised flying stand for Epic-scale (6mm) aircraft.

The stand is a solid of revolution: a chamfered disc, a filleted tapering
stem, and a flared pad on top for gluing (or pinning) the model. A disc
magnet sits flush in a pocket in the underside of the base, centred under
the stem, so the stand sticks to steel sheet, trays or magnetic storage.

Writes a binary STL and an equivalent OpenSCAD file (rotate_extrude of the
same profile), so it can be printed directly or tweaked in OpenSCAD.

    python3 flying_base.py                     # defaults: 40mm base, 10x2 magnet
    python3 flying_base.py --magnet-d 6 --magnet-h 3 --pin-d 0 -o no_pin
"""
import argparse
import math
import struct
from pathlib import Path


def profile(a):
    """Closed (r, z) outline, starting and ending on the axis (r = 0)."""
    R = a.base_d / 2
    top = a.height
    pocket_r = (a.magnet_d + a.clearance) / 2
    pocket_h = a.magnet_h + a.magnet_recess
    base_h = max(a.base_h, pocket_h + a.magnet_roof)
    pad_r = a.pad_d / 2
    stem_bot = a.stem_bottom_d / 2
    stem_top = a.stem_top_d / 2
    f = a.fillet

    if pocket_r >= R - a.bottom_chamfer - 1:
        raise SystemExit("magnet is too wide for this base")
    if stem_top > pad_r:
        raise SystemExit("stem top must not be wider than the top pad")
    if top - a.pad_h - a.cup_flare <= base_h + f:
        raise SystemExit("stand too short for this base, fillet and top pad")

    # Magnet pocket in the underside, centred under the stem where the
    # part is thickest, so the pocket costs no strength at the stem joint.
    pts = [
        (0.0, pocket_h),
        (pocket_r, pocket_h),
        (pocket_r, 0.0),
        (R - a.bottom_chamfer, 0.0),
        (R, a.bottom_chamfer),
        (R, base_h - a.top_chamfer),
        (R - a.top_chamfer * 2, base_h),
    ]
    # Concave fillet where the stem meets the disc (most of the bending load).
    cx, cz = stem_bot + f, base_h + f
    steps = 16
    for i in range(steps + 1):
        t = math.radians(-90 - 90 * i / steps)
        pts.append((cx + f * math.cos(t), cz + f * math.sin(t)))
    # Flared glue pad on top of the stem for the model.
    pts += [
        (stem_top, top - a.pad_h - a.cup_flare),
        (pad_r, top - a.pad_h),
        (pad_r, top - 0.4),
        (pad_r - 0.4, top),
    ]
    if a.pin_d:
        pts += [(a.pin_d / 2, top), (a.pin_d / 2, top - a.pin_depth), (0.0, top - a.pin_depth)]
    else:
        pts.append((0.0, top))
    return pts


def revolve(pts, n):
    verts, rings = [], []
    for r, z in pts:
        if r == 0:
            rings.append([len(verts)] * n)
            verts.append((0.0, 0.0, z))
        else:
            start = len(verts)
            for i in range(n):
                t = 2 * math.pi * i / n
                verts.append((r * math.cos(t), r * math.sin(t), z))
            rings.append(list(range(start, start + n)))
    faces = []
    m = len(pts)
    for k in range(m - 1 if pts[0][0] == 0 and pts[-1][0] == 0 else m):
        A, B = rings[k], rings[(k + 1) % m]
        for i in range(n):
            j = (i + 1) % n
            for tri in ((A[i], B[i], B[j]), (A[i], B[j], A[j])):
                if len(set(tri)) == 3:
                    faces.append(tri)
    return verts, faces


def signed_volume(verts, faces):
    v = 0.0
    for a, b, c in faces:
        (x1, y1, z1), (x2, y2, z2), (x3, y3, z3) = verts[a], verts[b], verts[c]
        v += (x1 * (y2 * z3 - z2 * y3) - y1 * (x2 * z3 - z2 * x3) + z1 * (x2 * y3 - y2 * x3)) / 6
    return v


def check_closed(faces):
    edges = {}
    for a, b, c in faces:
        for e in ((a, b), (b, c), (c, a)):
            edges[e] = edges.get(e, 0) + 1
    bad = [e for e, k in edges.items() if k != 1 or edges.get((e[1], e[0])) != 1]
    return not bad


def write_stl(path, verts, faces):
    with open(path, "wb") as fh:
        fh.write(b"Epic flying base".ljust(80, b" "))
        fh.write(struct.pack("<I", len(faces)))
        for a, b, c in faces:
            p, q, r = verts[a], verts[b], verts[c]
            u = [q[i] - p[i] for i in range(3)]
            w = [r[i] - p[i] for i in range(3)]
            nx, ny, nz = u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0]
            ln = math.sqrt(nx * nx + ny * ny + nz * nz) or 1.0
            fh.write(struct.pack("<12fH", nx / ln, ny / ln, nz / ln, *p, *q, *r, 0))


def write_scad(path, pts, n):
    poly = ",\n    ".join(f"[{r:.3f}, {z:.3f}]" for r, z in pts)
    path.write_text(
        "// Epic flying base, generated by flying_base.py\n"
        f"rotate_extrude($fn = {n})\n  polygon([\n    {poly}\n  ]);\n"
    )


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = p.add_argument
    g("-o", "--out", default="flying_base", help="output basename (.stl and .scad)")
    g("--base-d", type=float, default=40.0, help="base diameter")
    g("--base-h", type=float, default=3.5, help="base thickness")
    g("--top-chamfer", type=float, default=1.0)
    g("--bottom-chamfer", type=float, default=0.4)
    g("--height", type=float, default=45.0, help="overall height, table to cup rim")
    g("--stem-bottom-d", type=float, default=7.0)
    g("--stem-top-d", type=float, default=5.0)
    g("--fillet", type=float, default=5.0, help="radius of the stem-to-base fillet")
    g("--magnet-d", type=float, default=10.0, help="magnet diameter")
    g("--magnet-h", type=float, default=2.0, help="magnet thickness")
    g("--magnet-recess", type=float, default=0.0, help="extra pocket depth (sink magnet above the table)")
    g("--magnet-roof", type=float, default=1.5, help="minimum material above the pocket; base thickens to keep it")
    g("--clearance", type=float, default=0.2, help="added to pocket diameter (0.1 resin, 0.2 FDM)")
    g("--pad-d", type=float, default=7.0, help="diameter of the glue pad on top of the stem")
    g("--pad-h", type=float, default=1.5)
    g("--cup-flare", type=float, default=3.0, help="height of the cone from stem to pad")
    g("--pin-d", type=float, default=1.5, help="hole in the pad for a pin; 1.5 fits ~1mm paper clip wire on FDM, use 1.1 for resin (0 = none)")
    g("--pin-depth", type=float, default=6.0)
    g("--segments", type=int, default=128)
    a = p.parse_args()

    pts = profile(a)
    verts, faces = revolve(pts, a.segments)
    if signed_volume(verts, faces) < 0:
        faces = [(x, z, y) for x, y, z in faces]
    if not check_closed(faces):
        raise SystemExit("mesh is not watertight; check parameters")

    out = Path(a.out)
    write_stl(out.with_suffix(".stl"), verts, faces)
    write_scad(out.with_suffix(".scad"), pts, a.segments)
    vol = signed_volume(verts, faces)
    print(f"{out.with_suffix('.stl')}: {len(faces)} triangles, {vol / 1000:.2f} cm3 "
          f"(~{vol / 1000 * 1.24:.1f} g PLA), watertight")


if __name__ == "__main__":
    main()
